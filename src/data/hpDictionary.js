/**
 * Intelligent English Stemming & Lemmatization for Primary & Junior Learners
 * Helps students click past tenses (whispered -> whisper), plurals (fences -> fence),
 * and gerunds (craning -> crane) without failing dictionary lookups.
 */
export function getStemCandidates(word) {
  if (!word) return [];
  const w = word.toLowerCase();
  const candidates = [w];

  if (w.endsWith("'s") || w.endsWith("’s")) {
    candidates.push(w.slice(0, -2));
  }
  if (w.endsWith('ies') && w.length > 4) {
    candidates.push(w.slice(0, -3) + 'y');
  }
  if (w.endsWith('es') && w.length > 3) {
    candidates.push(w.slice(0, -2));
    candidates.push(w.slice(0, -1));
  }
  if (w.endsWith('s') && !w.endsWith('ss') && w.length > 2) {
    candidates.push(w.slice(0, -1));
  }
  if (w.endsWith('ing') && w.length > 4) {
    const base = w.slice(0, -3);
    candidates.push(base);
    candidates.push(base + 'e');
    if (base.length > 2 && base[base.length - 1] === base[base.length - 2]) {
      candidates.push(base.slice(0, -1));
    }
  }
  if (w.endsWith('ed') && w.length > 3) {
    const base = w.slice(0, -2);
    candidates.push(base);
    candidates.push(w.slice(0, -1));
    if (base.length > 2 && base[base.length - 1] === base[base.length - 2]) {
      candidates.push(base.slice(0, -1));
    }
    if (base.endsWith('i')) {
      candidates.push(base.slice(0, -1) + 'y');
    }
  }
  if (w.endsWith('ly') && w.length > 3) {
    const base = w.slice(0, -2);
    candidates.push(base);
    if (base.endsWith('i')) {
      candidates.push(base.slice(0, -1) + 'y');
    }
  }
  return [...new Set(candidates)];
}

// Async function to lookup word in local HP glossary or Free Dictionary API
export async function lookupWord(rawWord) {
  if (!rawWord) return null;
  // Clean punctuation from word
  const cleanWord = rawWord.replace(/[^a-zA-Z'’-]/g, '').trim().toLowerCase();
  if (!cleanWord) return null;

  // 1. Try local glossary with lemmatization candidates first (0ms latency, 100% pure Chinese)
  const candidates = getStemCandidates(cleanWord);
  for (const c of candidates) {
    if (HP_LORE_DICTIONARY[c]) {
      const item = HP_LORE_DICTIONARY[c];
      return {
        word: rawWord,
        baseWord: item.word,
        phonetic: item.phonetic || '',
        pos: item.pos || '单词',
        translation: item.translation,
        lore: item.lore || null,
        isHpLore: Boolean(item.lore),
        audioUrl: null
      };
    }
  }

  // Fallback to online dictionary for phonetics & POS
  try {
    const res = await fetch(`https://api.dictionaryapi.dev/api/v2/entries/en/${cleanWord}`);
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        const entry = data[0];
        const audioObj = entry.phonetics?.find(p => p.audio && p.audio.length > 0);
        const meaning = entry.meanings?.[0];

        // Pos translation to Chinese
        const posMap = {
          noun: '名词',
          verb: '动词',
          adjective: '形容词',
          adverb: '副词',
          pronoun: '代词',
          preposition: '介词',
          conjunction: '连词'
        };
        const rawPos = meaning?.partOfSpeech || 'word';
        const cnPos = posMap[rawPos] || rawPos;

        // Try to fetch Chinese definition from free translation API
        let cnTranslation = '';
        try {
          const transRes = await fetch(`https://api.mymemory.translated.net/get?q=${cleanWord}&langpair=en|zh`);
          if (transRes.ok) {
            const transData = await transRes.json();
            const translatedText = transData.responseData?.translatedText;
            if (translatedText && !translatedText.toLowerCase().includes('error')) {
              cnTranslation = translatedText;
            }
          }
        } catch {}

        return {
          word: entry.word,
          phonetic: entry.phonetic || entry.phonetics?.[0]?.text || '',
          pos: cnPos,
          translation: cnTranslation || `【${cnPos}】可点击底部“有道词典”或“剑桥双解”详查`,
          lore: null,
          isHpLore: false,
          audioUrl: audioObj?.audio || null
        };
      }
    }
  } catch (err) {
    console.warn('Online dictionary fetch error:', err);
  }

  // Default fallback if offline or not found
  return {
    word: cleanWord,
    phonetic: '',
    pos: '单词',
    translation: '可点击底部“有道词典”或“剑桥双解”查看中文释义',
    lore: null,
    isHpLore: false,
    audioUrl: null
  };
}
