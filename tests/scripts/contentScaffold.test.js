import { describe, it, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { scaffoldContent } from '../../scripts/content-scaffold.js';
import { validateVttContent, compileContentFeed } from '../../scripts/content-compiler.js';

const execFileAsync = promisify(execFile);
const SCAFFOLD_SCRIPT_PATH = path.resolve('scripts/content-scaffold.js');

describe('Content Scaffold Generator', () => {
  let tmpDir;

  beforeEach(async () => {
    tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'hogwarts-scaffold-test-'));
  });

  afterEach(async () => {
    if (tmpDir) {
      await fs.rm(tmpDir, { recursive: true, force: true });
    }
  });

  describe('scaffoldContent - TED talk template', () => {
    it('creates standard TED directory structure with meta.json, subtitle.vtt, and README.txt', async () => {
      const result = await scaffoldContent(tmpDir, {
        type: 'ted',
        id: 'how-magic-works',
        title: 'How Magic Works',
        speaker: 'Albus Dumbledore'
      });

      assert.equal(result.success, true);
      assert.ok(result.createdFiles.length >= 3);
      assert.equal(result.errors?.length || 0, 0);

      const targetDir = path.join(tmpDir, 'ted', 'how-magic-works');
      assert.equal(result.targetDir, targetDir);

      // Verify meta.json content
      const metaRaw = await fs.readFile(path.join(targetDir, 'meta.json'), 'utf-8');
      const meta = JSON.parse(metaRaw);
      assert.equal(meta.id, 'how-magic-works');
      assert.equal(meta.title, 'How Magic Works');
      assert.equal(meta.speaker, 'Albus Dumbledore');
      assert.equal(meta.duration, 0);
      assert.equal(meta.difficulty, 'Intermediate');
      assert.equal(meta.topic, 'General');
      assert.equal(meta.description, 'Standard TED talk template generated by Hogwarts Audio scaffold.');

      // Verify subtitle.vtt syntax and validity
      const vttContent = await fs.readFile(path.join(targetDir, 'subtitle.vtt'), 'utf-8');
      assert.match(vttContent, /^WEBVTT/);
      const vttValidation = validateVttContent(vttContent);
      assert.equal(vttValidation.valid, true);
      assert.ok(vttValidation.cuesCount >= 1);

      // Verify README.txt instructions
      const readme = await fs.readFile(path.join(targetDir, 'README.txt'), 'utf-8');
      assert.match(readme, /video\.mp4/i);
    });

    it('applies standard defaults when optional fields are omitted', async () => {
      const result = await scaffoldContent(tmpDir, {
        type: 'ted',
        id: 'ancient-runes-intro'
      });

      assert.equal(result.success, true);
      const metaRaw = await fs.readFile(path.join(result.targetDir, 'meta.json'), 'utf-8');
      const meta = JSON.parse(metaRaw);
      assert.equal(meta.id, 'ancient-runes-intro');
      assert.equal(meta.title, 'Ancient Runes Intro');
      assert.equal(meta.speaker, 'TED Speaker');
    });
  });

  describe('scaffoldContent - Podcast series & episode template', () => {
    it('creates standard podcast structure with root meta.json and episode ep01 template', async () => {
      const result = await scaffoldContent(tmpDir, {
        type: 'podcast',
        id: 'hp-book-1',
        title: "Harry Potter and the Sorcerer's Stone",
        chapter: 1,
        author: 'J.K. Rowling',
        narrator: 'Stephen Fry'
      });

      assert.equal(result.success, true);
      const targetDir = path.join(tmpDir, 'podcasts', 'hp-book-1');
      assert.equal(result.targetDir, targetDir);

      // Verify root meta.json
      const rootMetaRaw = await fs.readFile(path.join(targetDir, 'meta.json'), 'utf-8');
      const rootMeta = JSON.parse(rootMetaRaw);
      assert.equal(rootMeta.id, 'hp-book-1');
      assert.equal(rootMeta.title, "Harry Potter and the Sorcerer's Stone");
      assert.equal(rootMeta.author, 'J.K. Rowling');
      assert.equal(rootMeta.narrator, 'Stephen Fry');
      assert.equal(rootMeta.series, 'Harry Potter');
      assert.equal(rootMeta.cover, 'cover.jpg');

      // Verify episode ep01 files
      const epDir = path.join(targetDir, 'episodes', 'ep01');
      const epMetaRaw = await fs.readFile(path.join(epDir, 'meta.json'), 'utf-8');
      const epMeta = JSON.parse(epMetaRaw);
      assert.equal(epMeta.chapter, 1);
      assert.equal(epMeta.title, 'Chapter 1');
      assert.equal(epMeta.audio, 'audio.mp3');
      assert.equal(epMeta.vtt, 'subtitles.vtt');

      // Verify subtitles.vtt syntax and validity
      const vttContent = await fs.readFile(path.join(epDir, 'subtitles.vtt'), 'utf-8');
      assert.match(vttContent, /^WEBVTT/);
      const vttValidation = validateVttContent(vttContent);
      assert.equal(vttValidation.valid, true);
      assert.ok(vttValidation.cuesCount >= 1);

      // Verify README.txt
      const readme = await fs.readFile(path.join(epDir, 'README.txt'), 'utf-8');
      assert.match(readme, /audio\.mp3/i);
    });

    it('pads episode chapter numbers correctly (e.g. chapter 7 -> ep07)', async () => {
      const result = await scaffoldContent(tmpDir, {
        type: 'podcast',
        id: 'hp-book-2',
        chapter: 7
      });

      assert.equal(result.success, true);
      const epDir = path.join(result.targetDir, 'episodes', 'ep07');
      const exists = await fs.access(epDir).then(() => true).catch(() => false);
      assert.equal(exists, true);

      const epMetaRaw = await fs.readFile(path.join(epDir, 'meta.json'), 'utf-8');
      const epMeta = JSON.parse(epMetaRaw);
      assert.equal(epMeta.chapter, 7);
      assert.equal(epMeta.title, 'Chapter 7');
    });
  });

  describe('scaffoldContent - Validation and Protection', () => {
    it('rejects missing or unsupported content type', async () => {
      const missingResult = await scaffoldContent(tmpDir, { id: 'test-id' });
      assert.equal(missingResult.success, false);
      assert.ok(missingResult.errors.some(e => e.includes('type')));

      const invalidResult = await scaffoldContent(tmpDir, { type: 'unsupported', id: 'test-id' });
      assert.equal(invalidResult.success, false);
      assert.ok(invalidResult.errors.some(e => e.includes('unsupported') || e.includes('type')));
    });

    it('rejects missing or invalid slug/id', async () => {
      const missingId = await scaffoldContent(tmpDir, { type: 'ted' });
      assert.equal(missingId.success, false);
      assert.ok(missingId.errors.some(e => e.includes('id')));

      const invalidSlug = await scaffoldContent(tmpDir, { type: 'ted', id: '../traversal' });
      assert.equal(invalidSlug.success, false);
      assert.ok(invalidSlug.errors.some(e => e.includes('slug') || e.includes('invalid') || e.includes('id')));
    });

    it('prevents accidental overwrite when target directory already exists without --force', async () => {
      // First creation succeeds
      const first = await scaffoldContent(tmpDir, { type: 'ted', id: 'existing-talk' });
      assert.equal(first.success, true);

      // Second creation without force fails safely
      const second = await scaffoldContent(tmpDir, { type: 'ted', id: 'existing-talk' });
      assert.equal(second.success, false);
      assert.ok(second.errors.some(e => e.includes('already exists')));

      // With force: true, succeeds
      const third = await scaffoldContent(tmpDir, { type: 'ted', id: 'existing-talk', force: true });
      assert.equal(third.success, true);
    });
  });

  describe('Integration with content-compiler', () => {
    it('scaffolded TED talk compiles with 0 errors when media file is present', async () => {
      const scaffoldResult = await scaffoldContent(tmpDir, {
        type: 'ted',
        id: 'defense-against-dark-arts',
        title: 'Defense Against the Dark Arts',
        speaker: 'Remus Lupin'
      });
      assert.equal(scaffoldResult.success, true);

      // Add dummy video file to satisfy media presence requirement
      await fs.writeFile(path.join(scaffoldResult.targetDir, 'video.mp4'), 'mock-video-stream');

      const compileResult = await compileContentFeed(tmpDir, { dryRun: true });
      assert.equal(compileResult.errors.length, 0);
      assert.equal(compileResult.stats.tedTalksCount, 1);
      assert.equal(compileResult.feed.ted[0].speaker, 'Remus Lupin');
    });

    it('scaffolded podcast compiles with 0 errors when media file is present', async () => {
      const scaffoldResult = await scaffoldContent(tmpDir, {
        type: 'podcast',
        id: 'hp-book-1',
        title: "Harry Potter and the Philosopher's Stone",
        chapter: 1
      });
      assert.equal(scaffoldResult.success, true);

      // Add dummy audio file in episode folder
      const epDir = path.join(scaffoldResult.targetDir, 'episodes', 'ep01');
      await fs.writeFile(path.join(epDir, 'audio.mp3'), 'mock-audio-stream');

      const compileResult = await compileContentFeed(tmpDir, { dryRun: true });
      assert.equal(compileResult.errors.length, 0);
      assert.equal(compileResult.stats.booksCount, 1);
      assert.equal(compileResult.feed.podcasts[0].chapters.length, 1);
    });
  });

  describe('CLI Command Line Execution', () => {
    it('shows usage guide and exits with code 1 when required arguments are missing', async () => {
      try {
        await execFileAsync('node', [SCAFFOLD_SCRIPT_PATH]);
        assert.fail('Should have exited with code 1');
      } catch (err) {
        assert.equal(err.code, 1);
        const output = (err.stdout || '') + (err.stderr || '');
        assert.match(output, /Usage:/i);
        assert.match(output, /--type/);
      }
    });

    it('prints help message with --help flag and exits with code 0', async () => {
      const { stdout } = await execFileAsync('node', [SCAFFOLD_SCRIPT_PATH, '--help']);
      assert.match(stdout, /Hogwarts Audio Content Scaffold/i);
      assert.match(stdout, /--type/);
    });

    it('scaffolds directory successfully from CLI arguments', async () => {
      const talkId = 'cli-test-talk';
      const { stdout } = await execFileAsync('node', [
        SCAFFOLD_SCRIPT_PATH,
        `--content-dir=${tmpDir}`,
        '--type=ted',
        `--id=${talkId}`,
        '--title=CLI Test Talk',
        '--speaker=Minerva McGonagall'
      ]);

      assert.match(stdout, /scaffold completed/i);
      const metaExists = await fs.access(path.join(tmpDir, 'ted', talkId, 'meta.json')).then(() => true).catch(() => false);
      assert.equal(metaExists, true);
    });
  });
});
