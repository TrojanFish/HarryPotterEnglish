import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Capitalizes a slug into a display title.
 * e.g. "how-magic-works" -> "How Magic Works"
 * @param {string} slug
 * @returns {string}
 */
function slugToTitle(slug) {
  return slug
    .split(/[-_]+/)
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * Scaffolds a new content directory with standard meta.json and subtitle templates.
 * @param {string} contentDir - Target root content directory (e.g. content/)
 * @param {object} options
 * @param {'ted' | 'podcast'} options.type - Content type to scaffold
 * @param {string} options.id - Safe slug/ID for the content (e.g. 'how-magic-works', 'hp-book-1')
 * @param {string} [options.title] - Optional display title
 * @param {string} [options.speaker] - Optional TED speaker name
 * @param {number} [options.chapter] - Optional chapter number for podcasts (defaults to 1)
 * @param {string} [options.author] - Optional podcast author (defaults to 'J.K. Rowling')
 * @param {string} [options.narrator] - Optional narrator (defaults to 'Stephen Fry')
 * @param {boolean} [options.force] - Whether to overwrite existing directory
 * @returns {Promise<{ success: boolean, targetDir: string, createdFiles: string[], errors?: string[] }>}
 */
export async function scaffoldContent(contentDir, options = {}) {
  const errors = [];

  if (!contentDir || typeof contentDir !== 'string') {
    return {
      success: false,
      targetDir: '',
      createdFiles: [],
      errors: ['Target content directory is required and must be a valid path string.']
    };
  }

  const rawType = (options.type || '').trim().toLowerCase();
  if (rawType !== 'ted' && rawType !== 'podcast') {
    return {
      success: false,
      targetDir: '',
      createdFiles: [],
      errors: ['Invalid or missing content type. Must be "ted" or "podcast".']
    };
  }

  const rawId = (options.id || '').trim();
  if (!rawId || !/^[a-zA-Z0-9_-]+$/.test(rawId)) {
    return {
      success: false,
      targetDir: '',
      createdFiles: [],
      errors: ['Invalid content ID/slug. Must contain only alphanumeric characters, dashes, and underscores.']
    };
  }

  const resolvedContentDir = path.resolve(contentDir);
  const targetSubdir = rawType === 'ted' ? 'ted' : 'podcasts';
  const targetDir = path.join(resolvedContentDir, targetSubdir, rawId);

  // Check if directory already exists
  let dirExists = false;
  try {
    await fs.access(targetDir);
    dirExists = true;
  } catch {
    dirExists = false;
  }

  if (dirExists && !options.force) {
    return {
      success: false,
      targetDir,
      createdFiles: [],
      errors: [`Target directory already exists: ${targetDir}. Use --force to overwrite.`]
    };
  }

  const createdFiles = [];
  const displayTitle = (options.title || '').trim() || slugToTitle(rawId);

  try {
    if (rawType === 'ted') {
      await fs.mkdir(targetDir, { recursive: true });

      const speakerName = (options.speaker || '').trim() || 'TED Speaker';
      const meta = {
        id: rawId,
        title: displayTitle,
        speaker: speakerName,
        duration: 0,
        difficulty: 'Intermediate',
        topic: 'General',
        description: 'Standard TED talk template generated by Hogwarts Audio scaffold.'
      };

      const metaPath = path.join(targetDir, 'meta.json');
      await fs.writeFile(metaPath, JSON.stringify(meta, null, 2) + '\n', 'utf-8');
      createdFiles.push(metaPath);

      const vttContent = [
        'WEBVTT - Hogwarts Audio Bilingual Subtitles',
        '',
        '00:00.000 --> 00:05.000',
        'Welcome to this Hogwarts presentation.',
        '欢迎收看本次霍格沃茨讲座。',
        ''
      ].join('\n');

      const vttPath = path.join(targetDir, 'subtitle.vtt');
      await fs.writeFile(vttPath, vttContent, 'utf-8');
      createdFiles.push(vttPath);

      const readmeContent = [
        'Drop your video file (video.mp4 or video.webm) and optional cover.jpg in this folder.',
        ''
      ].join('\n');

      const readmePath = path.join(targetDir, 'README.txt');
      await fs.writeFile(readmePath, readmeContent, 'utf-8');
      createdFiles.push(readmePath);
    } else {
      // Podcast scaffolding
      await fs.mkdir(targetDir, { recursive: true });

      const authorName = (options.author || '').trim() || 'J.K. Rowling';
      const narratorName = (options.narrator || '').trim() || 'Stephen Fry';
      const chapterNum = Math.max(1, parseInt(options.chapter, 10) || 1);
      const epFolder = `ep${String(chapterNum).padStart(2, '0')}`;
      const epDir = path.join(targetDir, 'episodes', epFolder);
      await fs.mkdir(epDir, { recursive: true });

      const rootMeta = {
        id: rawId,
        title: displayTitle,
        author: authorName,
        narrator: narratorName,
        series: 'Harry Potter',
        cover: 'cover.jpg',
        description: 'Standard podcast series template generated by Hogwarts Audio scaffold.'
      };

      const rootMetaPath = path.join(targetDir, 'meta.json');
      await fs.writeFile(rootMetaPath, JSON.stringify(rootMeta, null, 2) + '\n', 'utf-8');
      createdFiles.push(rootMetaPath);

      const epMeta = {
        chapter: chapterNum,
        title: `Chapter ${chapterNum}`,
        audio: 'audio.mp3',
        vtt: 'subtitles.vtt'
      };

      const epMetaPath = path.join(epDir, 'meta.json');
      await fs.writeFile(epMetaPath, JSON.stringify(epMeta, null, 2) + '\n', 'utf-8');
      createdFiles.push(epMetaPath);

      const vttContent = [
        'WEBVTT - Hogwarts Audio Bilingual Subtitles',
        '',
        '00:00.000 --> 00:05.000',
        'Mr and Mrs Dursley, of number four, Privet Drive.',
        '家住女贞路4号的德思礼夫妇。',
        ''
      ].join('\n');

      const vttPath = path.join(epDir, 'subtitles.vtt');
      await fs.writeFile(vttPath, vttContent, 'utf-8');
      createdFiles.push(vttPath);

      const readmeContent = [
        'Drop your audio file (audio.mp3 or audio.m4a) in this episode folder.',
        ''
      ].join('\n');

      const readmePath = path.join(epDir, 'README.txt');
      await fs.writeFile(readmePath, readmeContent, 'utf-8');
      createdFiles.push(readmePath);
    }

    return {
      success: true,
      targetDir,
      createdFiles,
      errors: []
    };
  } catch (err) {
    return {
      success: false,
      targetDir,
      createdFiles,
      errors: [`Scaffold generation failed: ${err.message}`]
    };
  }
}

/**
 * Parses command line arguments.
 * @param {string[]} args
 * @returns {Record<string, any>}
 */
function parseCliArgs(args) {
  const result = {};
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--help' || arg === '-h') {
      result.help = true;
    } else if (arg === '--force') {
      result.force = true;
    } else if (arg.startsWith('--')) {
      const eqIdx = arg.indexOf('=');
      if (eqIdx !== -1) {
        const key = arg.slice(2, eqIdx);
        const val = arg.slice(eqIdx + 1);
        result[key] = val;
      } else {
        const key = arg.slice(2);
        if (i + 1 < args.length && !args[i + 1].startsWith('--')) {
          result[key] = args[i + 1];
          i++;
        } else {
          result[key] = true;
        }
      }
    }
  }
  return result;
}

function printUsage() {
  console.log(`Hogwarts Audio Content Scaffold Generator

Usage:
  node scripts/content-scaffold.js --type=<ted|podcast> --id=<slug> [options]

Required Options:
  --type=<ted|podcast>    Type of content to scaffold
  --id=<slug>             Safe unique identifier (e.g. how-magic-works, hp-book-1)

Optional Options:
  --title=<title>         Display title
  --speaker=<speaker>     Speaker name (TED only)
  --chapter=<number>      Initial chapter number (Podcast only, defaults to 1)
  --author=<author>       Author name (Podcast only, defaults to J.K. Rowling)
  --narrator=<narrator>   Narrator name (Podcast only, defaults to Stephen Fry)
  --content-dir=<path>    Target content root directory (defaults to ./content)
  --force                 Overwrite existing folder if present
  --help, -h              Show this help message

Examples:
  node scripts/content-scaffold.js --type=ted --id=how-magic-works --title="How Magic Works" --speaker="Albus Dumbledore"
  node scripts/content-scaffold.js --type=podcast --id=hp-book-1 --title="Harry Potter and the Sorcerer's Stone" --chapter=1
`);
}

// CLI direct execution entrypoint
const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (isMain) {
  (async () => {
    const cliArgs = parseCliArgs(process.argv.slice(2));

    if (cliArgs.help) {
      printUsage();
      process.exit(0);
    }

    const type = cliArgs.type;
    const id = cliArgs.id;
    const contentDir = cliArgs['content-dir'] || cliArgs.dir || path.resolve(process.cwd(), 'content');

    if (!type || !id) {
      console.error('[Content Scaffold Error] Missing required arguments: --type and --id are required.\n');
      printUsage();
      process.exit(1);
    }

    const result = await scaffoldContent(contentDir, {
      type,
      id,
      title: cliArgs.title,
      speaker: cliArgs.speaker,
      chapter: cliArgs.chapter ? parseInt(cliArgs.chapter, 10) : undefined,
      author: cliArgs.author,
      narrator: cliArgs.narrator,
      force: Boolean(cliArgs.force)
    });

    if (!result.success) {
      console.error('[Content Scaffold Error]');
      for (const err of result.errors || []) {
        console.error(`  - ${err}`);
      }
      process.exit(1);
    }

    console.log('[Content Scaffold] Scaffold completed successfully:');
    console.log(`  - Type: ${type}`);
    console.log(`  - Target directory: ${result.targetDir}`);
    console.log('  - Created files:');
    for (const f of result.createdFiles) {
      console.log(`    - ${f}`);
    }
    process.exit(0);
  })();
}
